import {chromium} from 'playwright';
import {mkdir,copyFile,writeFile} from 'node:fs/promises';
await mkdir('public/captures/raw',{recursive:true});
const browser = await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH ?? 'C:/Users/Andrii/AppData/Local/ms-playwright/chromium-1243/chrome-win64/chrome.exe'});
const context = await browser.newContext({viewport:{width:1600,height:900},recordVideo:{dir:'public/captures/raw',size:{width:1600,height:900}}});
const page = await context.newPage();
await page.goto('http://127.0.0.1:5173');
await page.waitForTimeout(16000);
const start = Date.now();
const marks = {};
async function mark(name) {marks[name] = (Date.now()-start)/1000; console.log(name,marks[name]);}
await page.getByRole('button',{name:'Fit',exact:true}).click();
await page.waitForTimeout(1200);
await page.screenshot({path:'public/captures/overview.png'});
await mark('overview');
await page.getByRole('button',{name:'Restart demo',exact:true}).click();
await mark('conversation');
await page.waitForTimeout(14000);
await page.screenshot({path:'public/captures/conversation.png'});
await mark('accept');
const accept = page.getByRole('button',{name:'Accept',exact:true});
await accept.first().click();
await page.waitForTimeout(2200);
if(await accept.count()) await accept.first().click();
await page.waitForTimeout(2800);
await page.getByRole('button',{name:'Fit',exact:true}).click();
await page.waitForTimeout(1000);
await page.screenshot({path:'public/captures/accepted.png'});
await mark('accepted');
await page.waitForTimeout(3000);
const input = page.locator('input').first();
await input.fill('What breaks if I change performWorkOnRoot?');
await mark('blast');
await input.press('Enter');
await page.waitForTimeout(10000);
await page.getByRole('button',{name:'Fit',exact:true}).click();
await page.waitForTimeout(2000);
await page.screenshot({path:'public/captures/blast.png'});
await mark('blastReady');
await page.waitForTimeout(5500);
await writeFile('out/capture-marks.json',JSON.stringify(marks,null,2));
const video = page.video();
await context.close();
await copyFile(await video.path(),'public/captures/session.webm');
await browser.close();
